    for n,v in (("SimHealth",100),("SimStamina",100),("SimRetake",2),("SimCooldown",0),("SimDetection",0)):end=h.setvar(g,end,n,v)
    end=h.invoke(g,end,pawn,"PublishTestResources").find_then_pin()
    h.message(g,end,"ClearRetakeHistory",h.self_pin(g))
