"""Create only C-owned player and interactable doubles for the isolated F1 map."""
import unreal,sys,json,traceback
from pathlib import Path
repo=Path(unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_dir())).parent
sys.path.insert(0,str(repo/"Scripts/C"))
import blueprint_helpers_c as h
from importlib import reload
h=reload(h)
OUT={"passed":False,"saved":[]}
try:
    boolean=h.basic("bool");integer=h.basic("int")
    stealth=h.create_actor_bp("Narrative/Test","BP_TestStealth_C",h.asset("Enemies/BP_StealthComponent").generated_class())
    h.variable(stealth,"bTestHidden",boolean,False)
    h.variable(stealth,"HiddenChangeCount",integer,"0")
    g=h.override(stealth,"SetHidden");h.clear_body(g)
    end=h.setvar(g,g.find_graph_entry_pin(),"bTestHidden",h.param(g,"bHidden"))
    h.setvar(g,end,"HiddenChangeCount",h.math(g,"Add_IntInt",h.get(g,"HiddenChangeCount"),1))
    h.save(stealth);OUT["saved"].append(stealth.get_path_name())
    pawn=h.create_actor_bp("Narrative/Test","BP_TestPlayer_C",h.asset("Player/BP_PlayerCharacter").generated_class())
    h.variable(pawn,"bTestRetakeBlocked",boolean,False)
    h.variable(pawn,"RetakeHistoryClearCount",integer,"0")
    h.variable(pawn,"FocusChangeCount",integer,"0")
    h.variable(pawn,"LastFocusTarget",h.obj_type(unreal.Actor),"")
    h.variable(pawn,"LastFocusPrompt",h.basic("text"),"")
    h.add_component(pawn,"TestStealth",stealth.generated_class())
    camera=h.add_component(pawn,"TestCamera",unreal.CameraComponent)
    camera.set_editor_property("relative_location",unreal.Vector(-600,-600,900))
    camera.set_editor_property("relative_rotation",unreal.Rotator(-47,45,0))
    camera.set_editor_property("field_of_view",55.0)
    body=h.add_component(pawn,"TestBody",unreal.StaticMeshComponent)
    body.set_static_mesh(unreal.load_asset("/Engine/BasicShapes/Sphere"))
    body.set_editor_property("relative_scale3d",unreal.Vector(0.55,0.55,1.3))
    body.set_collision_enabled(unreal.CollisionEnabled.NO_COLLISION)
    h.compile_blueprint(pawn,warnings_as_errors=True)
    g=h.override(pawn,"GetStealthComponent");h.clear_body(g)
    h.result(g,g.find_graph_entry_pin(),Result=h.get(g,"TestStealth"))
    g,e=h.event(pawn,"SetRetakeBlocked")
    h.setvar(g,e.find_then_pin(),"bTestRetakeBlocked",e.find_output_pin("bBlocked"))
    g,e=h.event(pawn,"ClearRetakeHistory")
    h.setvar(g,e.find_then_pin(),"RetakeHistoryClearCount",h.math(g,"Add_IntInt",h.get(g,"RetakeHistoryClearCount"),1))
    g,e=h.event(pawn,"ReceiveBeginPlay")
    end,callback=h.bind_assign(g,e.find_then_pin(),h.get(g,"BP_InteractionComponent"),"OnFocusChanged")
    observed=h.setvar(g,callback.find_then_pin(),"FocusChangeCount",h.math(g,"Add_IntInt",h.get(g,"FocusChangeCount"),1))
    observed=h.setvar(g,observed,"LastFocusTarget",callback.find_output_pin("Target"))
    h.setvar(g,observed,"LastFocusPrompt",callback.find_output_pin("Prompt"))
    g,key=h.key_event(pawn,"E")
    h.invoke(g,key.find_output_pin("Pressed"),h.asset("Narrative/BP_InteractionComponent"),"TryInteract",target=h.get(g,"BP_InteractionComponent"))
    h.layout(pawn);h.save(pawn);OUT["saved"].append(pawn.get_path_name())
    stub=h.create_actor_bp("Narrative/Test","BP_TestInteractable_C",h.asset("Narrative/BP_InteractableBase").generated_class())
    h.variable(stub,"bConsumeAfterUse",boolean,True,True)
    h.variable(stub,"bReportJackFound",boolean,False,True)
    mesh=h.add_component(stub,"TestMesh",unreal.StaticMeshComponent)
    mesh.set_static_mesh(unreal.load_asset("/Engine/BasicShapes/Cube"))
    mesh.set_editor_property("relative_scale3d",unreal.Vector(0.45,0.45,0.7))
    mesh.set_editor_property("relative_location",unreal.Vector(0,0,35))
    g=h.override(stub,"ExecuteInteraction");h.clear_body(g)
    yes,no=h.branch(g,g.find_graph_entry_pin(),h.get(g,"bConsumeAfterUse"))
    done=h.setvar(g,yes,"bConsumed",True)
    branch=g.add_branch_node();h.connect(done,branch.find_execute_pin());h.connect(no,branch.find_execute_pin())
    h.connect(h.get(g,"bReportJackFound"),branch.find_input_pin("Condition"))
    h.invoke(g,branch.find_output_pin("then"),h.asset("Narrative/BP_InteractableBase"),"ReportStoryFact",Event="NewEnumerator0",Param="")
    h.layout(stub);h.save(stub);OUT["saved"].append(stub.get_path_name())
    mode=h.create_actor_bp("Narrative/Test","BP_TestGameMode_C",h.asset("Narrative/BP_GameMode").generated_class())
    h.compile_blueprint(mode,warnings_as_errors=True)
    cdo=unreal.get_default_object(mode.generated_class())
    cdo.set_editor_property("default_pawn_class",pawn.generated_class())
    cdo.set_editor_property("player_controller_class",unreal.PlayerController.static_class())
    h.save(mode);OUT["saved"].append(mode.get_path_name())
    OUT["passed"]=True
except Exception:OUT["error"]=traceback.format_exc()
finally:
    (repo/"Scripts/C/c_f1_test_doubles_build.json").write_text(json.dumps(OUT,indent=2),encoding="utf-8")
    print("C_F1_TEST_DOUBLES "+json.dumps(OUT))
