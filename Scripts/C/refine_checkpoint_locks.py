"""Checkpoint restore releases reversible C hideouts and reapplies narrative locks."""
import unreal,sys
from pathlib import Path
repo=Path(unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_dir())).parent
sys.path.insert(0,str(repo/"Scripts/C"))
import blueprint_helpers_c as h
from importlib import reload
h=reload(h)
objective=h.asset("Narrative/BP_ObjectiveManager");mode=h.asset("Narrative/BP_GameMode");hide=h.asset("Narrative/BP_Hideout");interaction=h.asset("Narrative/BP_InteractionComponent")
h.function(objective,"RestoreNarrativeInputLock")
h.compile_blueprint(objective,warnings_as_errors=True)
g=h.edit(objective,"RestoreNarrativeInputLock")
actual=h.any_true(g,h.get(g,"bDialogueActive"),h.get(g,"bDocumentActive"))
end=h.setvar(g,g.find_graph_entry_pin(),"bNarrativeInputLocked",h.not_(g,actual))
h.invoke(g,end,objective,"RefreshNarrativeInputLock")
h.layout(objective,["RestoreNarrativeInputLock"]);h.save(objective)
h.function(hide,"ResetOccupancy")
h.compile_blueprint(hide,warnings_as_errors=True)
g=h.edit(hide,"ResetOccupancy")
yes,_=h.branch(g,g.find_graph_entry_pin(),h.get(g,"bOccupied"))
end=h.setvar(g,yes,"bOccupied",False);end=h.setvar(g,end,"InteractionPrompt","Enter hideout")
yes,no=h.branch(g,end,h.is_valid(g,h.get(g,"Occupant")))
component=h.message(g,yes,"GetStealthComponent",h.get(g,"Occupant"))
end=h.invoke(g,component.find_then_pin(),h.asset("Enemies/BP_StealthComponent"),"SetHidden",target=component.find_result_pin(),bHidden=False).find_then_pin()
focus=h.call(g,"/Script/Engine.Actor:GetComponentByClass",target=h.get(g,"Occupant"),ComponentClass=interaction.generated_class().get_path_name()).find_result_pin()
end=h.invoke(g,end,interaction,"LockFocusTo",target=focus,Target=None).find_then_pin()
pc=h.call(g,"/Script/Engine.GameplayStatics:GetPlayerController",PlayerIndex=0).find_result_pin()
end=h.call(g,"/Script/Engine.Controller:SetIgnoreMoveInput",end,pc,bNewMoveInput=False).find_then_pin()
setter=g.add_set_member_variable_node("Occupant");h.literal(setter.find_input_pin("Occupant"),None)
h.connect(end,setter.find_execute_pin());h.connect(no,setter.find_execute_pin())
h.layout(hide,["ResetOccupancy"]);h.save(hide)
g=h.edit(mode,"RestoreCheckpoint")
gather=next(n for n in g.list_all_nodes() if "GetAllActorsWithInterface" in str(n.get_node_title()).replace(" ",""))
starts=gather.find_execute_pin().list_connected_pins();gather.find_execute_pin().break_pin_links()
all_hideouts=h.call(g,"/Script/Engine.GameplayStatics:GetAllActorsOfClass",ActorClass=hide.generated_class().get_path_name())
for start in starts:h.connect(start,all_hideouts.find_execute_pin())
body,item,done=h.foreach(g,all_hideouts.find_then_pin(),all_hideouts.find_output_pin("OutActors"))
h.invoke(g,body,hide,"ResetOccupancy",target=item);h.connect(done,gather.find_execute_pin())
restore_set=next(n for n in g.list_all_nodes() if n.get_class().get_name()=="K2Node_VariableSet" and "bRestoreInProgress" in str(n.get_node_title()) and not n.find_then_pin().list_connected_pins())
world_state=h.call(g,"/Script/Engine.GameplayStatics:GetGameState").find_result_pin()
manager=h.call(g,"/Script/Engine.Actor:GetComponentByClass",target=world_state,ComponentClass=objective.generated_class().get_path_name()).find_result_pin()
h.invoke(g,restore_set.find_then_pin(),objective,"RestoreNarrativeInputLock",target=manager)
h.layout(mode,["RestoreCheckpoint"]);h.save(mode)
# The double owns simulated input state. It derives the native movement lock from both reasons.
pawn=h.asset("Narrative/Test/BP_TestPlayer_C");g=h.edit(pawn,"EventGraph")
event=next(n for n in g.list_all_nodes() if n.get_class().get_name()=="K2Node_Event" and "SetGameplayInputEnabled" in str(n.get_node_title()).replace(" ",""))
event.find_then_pin().break_pin_links()
end=h.setvar(g,event.find_then_pin(),"bTestGameplayInputEnabled",event.find_output_pin("bEnabled"))
pc=h.call(g,"/Script/Engine.GameplayStatics:GetPlayerController",PlayerIndex=0).find_result_pin()
end=h.call(g,"/Script/Engine.Controller:ResetIgnoreMoveInput",end,pc).find_then_pin()
hidden=h.get(g,"bTestHidden",h.get(g,"TestStealth"),h.asset("Narrative/Test/BP_TestStealth_C").generated_class())
h.call(g,"/Script/Engine.Controller:SetIgnoreMoveInput",end,pc,bNewMoveInput=h.any_true(g,h.not_(g,event.find_output_pin("bEnabled")),hidden))
h.layout(pawn);h.save(pawn)
print("C_CHECKPOINT_LOCKS_READY")
