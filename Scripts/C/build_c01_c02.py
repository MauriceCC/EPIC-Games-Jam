"""Implement C-01/C-02 state and guarded transitions using Unreal Blueprint APIs.
Only BP_ObjectiveManager and BP_GameState are authored. No foreign gameplay system is edited.
"""
import unreal,json,traceback
from pathlib import Path
from toolset_registry.helpers import compile_blueprint
from editor_toolset.toolsets.blueprint import BlueprintTools
ROOT="/Game/Unscripted/"
OUT={"passed":False,"saved":[],"dependencies":[]}
manager=unreal.load_asset(ROOT+"Narrative/BP_ObjectiveManager")
state=unreal.load_asset(ROOT+"Narrative/BP_GameState")
mode=unreal.load_asset(ROOT+"Narrative/BP_GameMode")
interface=unreal.load_asset(ROOT+"Core/Interfaces/BPI_StoryEvents")
helper=unreal.get_default_object(unreal.load_class(None,"/Script/Engine.KismetNodeHelperLibrary"))

def enum_info(name):
    enum=unreal.load_asset(ROOT+"Core/Enums/"+name)
    values={}
    for i in range(255):
        raw=str(helper.call_method("GetEnumeratorName",args=(enum,i)))
        if raw=="None" or raw.endswith("_MAX"):break
        display=str(helper.call_method("GetEnumeratorUserFriendlyName",args=(enum,i)))
        values[display]={"index":i,"raw":raw.split("::")[-1]}
    t=unreal.EdGraphPinType()
    assert t.import_text('(PinCategory="byte",PinSubCategoryObject="'+enum.get_path_name()+'")')
    return enum,t,values
def edit(bp,name):
    graph=next((g for g in unreal.BlueprintEditorLibrary.list_graphs(bp) if g.get_name()==name),None)
    return unreal.BlueprintGraphEditor.get_graph_editor(graph) if graph else None
def connect(a,b):
    assert a and b and a.try_create_connection(b),(str(a),str(b))
def literal(pin,value):
    assert pin
    assert pin.set_pin_value("true" if value is True else "false" if value is False else str(value)),str(value)
def call(g,path):
    assert unreal.load_object(None,path),path
    return g.add_call_function_node(path)
def get(g,name):return g.add_get_member_variable_node(name).find_result_pin()
def setvar(g,start,name,value):
    node=g.add_set_member_variable_node(name)
    connect(start,node.find_execute_pin())
    if isinstance(value,unreal.BlueprintGraphPin):connect(value,node.find_input_pin(name))
    else:literal(node.find_input_pin(name),value)
    return node.find_then_pin()
def predicate(g,name,a,b=None):
    if name=="EqualEqual_ByteByte":
        options=[str(x) for x in g.list_available_nodes([a])]
        action=next(x for x in options if x.endswith("|Igual(enumerador)") or x.endswith("|Equal(Enum)"))
        node=g.create_node_from_name(action,unreal.Vector2D(0,0),[a])
        if not node.find_input_pin("A").list_connected_pins():connect(a,node.find_input_pin("A"))
        if isinstance(b,unreal.BlueprintGraphPin):connect(b,node.find_input_pin("B"))
        else:literal(node.find_input_pin("B"),"NewEnumerator"+str(b))
        return node.find_result_pin()
    node=call(g,"/Script/Engine.KismetMathLibrary:"+name)
    ins=[p for p in node.list_input_pins() if str(p.get_pin_name()) not in ("self",)]
    if isinstance(a,unreal.BlueprintGraphPin):connect(a,ins[0])
    else:literal(ins[0],a)
    if b is not None:
        if isinstance(b,unreal.BlueprintGraphPin):connect(b,ins[1])
        else:literal(ins[1],b)
    return node.find_result_pin()
def both(g,*items):
    result=items[0]
    for item in items[1:]:result=predicate(g,"BooleanAND",result,item)
    return result
def negate(g,value):return predicate(g,"Not_PreBool",value)
def phase_is(g,name):return predicate(g,"EqualEqual_ByteByte",get(g,"CurrentPhase"),PHASES[name]["index"])
def branch(g,start,cond):
    n=g.add_branch_node()
    connect(start,n.find_execute_pin());connect(cond,n.find_input_pin("Condition"))
    return n.find_output_pin("then"),n.find_output_pin("else")
def invoke(g,start,bp,name,values=None,target=None):
    n=call(g,bp.generated_class().get_path_name()+":"+name)
    connect(start,n.find_execute_pin())
    if target is not None:connect(target,n.find_self_pin())
    for name,value in (values or {}).items():
        if isinstance(value,unreal.BlueprintGraphPin):connect(value,n.find_input_pin(name))
        else:literal(n.find_input_pin(name),value)
    return n.find_then_pin(),n
def emit(g,start,name,values=None):
    actions=[str(a) for a in g.list_available_nodes([])]
    action=next(a for a in actions if a.endswith("|Call"+name))
    n=g.create_node_from_name(action,unreal.Vector2D(0,0),[])
    connect(start,n.find_execute_pin())
    for key,value in (values or {}).items():
        if isinstance(value,unreal.BlueprintGraphPin):connect(value,n.find_input_pin(key))
        else:literal(n.find_input_pin(key),value)
    return n.find_then_pin()
def commit(g,start,phase):
    return invoke(g,start,manager,"CommitStoryPhase",{"NewPhase":PHASES[phase]["raw"]})[0]
def new_function(bp,name,inputs=(),outputs=(),private=False):
    existing=edit(bp,name)
    if existing:
        # Only functions generated by this script may be rebuilt after an interrupted run.
        assert name in GENERATED_FUNCTIONS
        unreal.BlueprintEditorLibrary.remove_graph(bp,existing.get_graph())
    g=unreal.BlueprintGraphEditor.create_and_edit_function_graph(bp,name)
    for n,t in inputs:
        pin=g.add_graph_input_parameter(n,t)
        assert str(pin.get_pin_name())==n
    for n,t in outputs:g.add_graph_output_parameter(n,t)
    if private:g.set_function_is_private()
    return g
def param(g,name):return g.find_graph_entry_pin().get_owning_node().find_output_pin(name)
def annotate(g,text):
    # Layout the nodes; prose notes are stored in the C implementation report.
    for i,n in enumerate(g.list_all_nodes()):
        if n.get_class().get_name()!="EdGraphNode_Comment":
            n.set_node_pos(unreal.IntPoint((i%8)*340,(i//8)*220))
# Preserve a completed implementation if this one-time builder is run again.
existing_getter=edit(state,"GetCurrentPhase")
if existing_getter and any(n.get_class().get_name() not in ("K2Node_FunctionEntry","K2Node_FunctionResult") for n in existing_getter.list_all_nodes()):
    raise RuntimeError("C-01/C-02 already implemented. Run validate_c01_c02.py; do not rebuild authored graphs.")
try:
    event_enum,event_type,EVENTS=enum_info("EStoryEvent")
    phase_enum,phase_type,PHASES=enum_info("EStoryPhase")
    ending_enum,ending_type,ENDINGS=enum_info("EEndingType")
    assert set(PHASES)=={"FindJack","OpenEscapeRoute","ProtectJack","DiscoverTruth","FinalChoice","GameEnded"}
    assert set(ENDINGS)=={"None","OfficialCut","AuthenticRecord"}
    assert "SupervisorEncounterStarted" in EVENTS and len(EVENTS)==14
    actor_type=unreal.BlueprintEditorLibrary.get_object_reference_type(unreal.Actor.static_class())
    name_type=unreal.BlueprintEditorLibrary.get_basic_type_by_name("name")
    bool_type=unreal.BlueprintEditorLibrary.get_basic_type_by_name("bool")
    source=param(edit(interface,"ReportStoryEvent"),"Source")
    assert "/Script/Engine.Actor'" in source.get_pin_type().export_text()
    assert BlueprintTools.get_parent(manager)==unreal.ActorComponent.static_class()
    assert BlueprintTools.get_parent(state)==unreal.GameStateBase.static_class()
    assert BlueprintTools.get_parent(mode)==unreal.GameModeBase.static_class()
    for bp in (interface,manager,state,mode):
        compile_blueprint(bp,warnings_as_errors=True)
        OUT["dependencies"].append({"asset":bp.get_path_name(),"compiled":True})
    expected_dispatchers={"OnStoryPhaseChanged","OnChecklistUpdated","OnDialogueStarted","OnDialogueFinished","OnEndingTriggered"}
    assert {g.get_name() for g in BlueprintTools.list_event_dispatchers(manager)}==expected_dispatchers
    GENERATED_FUNCTIONS={"CommitStoryPhase","GetStoryPhase","HandleStoryEvent","ProcessStoryEvent","TryRecordEvidence","TryRegisterFinalDocument"}
    existing_own=[g for g in unreal.BlueprintEditorLibrary.list_graphs(manager) if g.get_name() in GENERATED_FUNCTIONS]
    for g in existing_own:unreal.BlueprintEditorLibrary.remove_graph(manager,g)
    compile_blueprint(manager,warnings_as_errors=True)
    base=unreal.BlueprintGraphEditor.get_graph_editor(unreal.BlueprintEditorLibrary.find_event_graph(manager))
    variables=[("CurrentPhase",phase_type,PHASES["FindJack"]["raw"]),("Ending",ending_type,ENDINGS["None"]["raw"])]
    variables += [(n,bool_type,"false") for n in ("bJackFound","bEscapeRouteOpen","bJackSafe","bEvidenceFound","bFalseReportFound","bSupervisorEncountered","bSupervisorDefeated","bIsProcessingStoryEvent")]
    for name,typ,default in variables:
        if unreal.BlueprintEditorLibrary.get_member_variable_type(manager,name) is None:
            assert base.add_member_variable(name,typ,default),name
        unreal.BlueprintEditorLibrary.set_blueprint_variable_instance_editable(manager,name,False)
        unreal.BlueprintEditorLibrary.set_blueprint_variable_category(manager,name,"Story State")
    inputs=[("Event",event_type),("Source",actor_type),("Param",name_type)]
    new_function(manager,"CommitStoryPhase",[("NewPhase",phase_type)],private=True)
    new_function(manager,"GetStoryPhase",outputs=[("Result",phase_type)])
    new_function(manager,"HandleStoryEvent",inputs)
    new_function(manager,"ProcessStoryEvent",inputs,private=True)
    new_function(manager,"TryRecordEvidence",[("Param",name_type)],private=True)
    new_function(manager,"TryRegisterFinalDocument",[("Param",name_type)],private=True)
    compile_blueprint(manager,warnings_as_errors=True)
    g=edit(manager,"CommitStoryPhase")
    yes,_=branch(g,g.find_graph_entry_pin(),negate(g,predicate(g,"EqualEqual_ByteByte",get(g,"CurrentPhase"),param(g,"NewPhase"))))
    end=setvar(g,yes,"CurrentPhase",param(g,"NewPhase"))
    end=emit(g,end,"OnStoryPhaseChanged",{"NewPhase":get(g,"CurrentPhase")})
    emit(g,end,"OnChecklistUpdated")
    annotate(g,"C-01/C-02: the sole runtime writer of CurrentPhase; broadcast only an actual transition.")
    g=edit(manager,"GetStoryPhase")
    result=next(n for n in g.list_all_nodes() if n.get_class().get_name()=="K2Node_FunctionResult")
    connect(g.find_graph_entry_pin(),result.find_execute_pin());connect(get(g,"CurrentPhase"),result.find_input_pin("Result"))
    g=edit(manager,"HandleStoryEvent")
    allowed=both(g,negate(g,get(g,"bIsProcessingStoryEvent")),negate(g,phase_is(g,"GameEnded")))
    yes,_=branch(g,g.find_graph_entry_pin(),allowed)
    end=setvar(g,yes,"bIsProcessingStoryEvent",True)
    end,_=invoke(g,end,manager,"ProcessStoryEvent",{name:param(g,name) for name,typ in inputs})
    setvar(g,end,"bIsProcessingStoryEvent",False)
    annotate(g,"C-01/C-02: terminal sessions and synchronous reentrant reports cannot skip or repeat transitions.")
    g=edit(manager,"TryRecordEvidence")
    yes,_=branch(g,g.find_graph_entry_pin(),both(g,phase_is(g,"DiscoverTruth"),get(g,"bJackSafe")))
    for token,flag in (("NursingRecord","bEvidenceFound"),("FabricatedReport","bFalseReportFound")):
        matched,yes=branch(g,yes,predicate(g,"EqualEqual_NameName",param(g,"Param"),token))
        fresh,_=branch(g,matched,negate(g,get(g,flag)))
        emit(g,setvar(g,fresh,flag,True),"OnChecklistUpdated")
    annotate(g,"C-02: record two distinct evidence facts only after refuge; no auto-reveal or evidence actor implementation. Param tokens are a provisional C convention.")
    g=edit(manager,"TryRegisterFinalDocument")
    condition=both(g,phase_is(g,"FinalChoice"),get(g,"bSupervisorDefeated"),predicate(g,"EqualEqual_ByteByte",get(g,"Ending"),ENDINGS["None"]["index"]))
    allowed,_=branch(g,g.find_graph_entry_pin(),condition)
    for token in ("OfficialCut","AuthenticRecord"):
        matched,allowed=branch(g,allowed,predicate(g,"EqualEqual_NameName",param(g,"Param"),token))
        end=setvar(g,matched,"Ending",ENDINGS[token]["raw"])
        end=commit(g,end,"GameEnded")
        emit(g,end,"OnEndingTriggered",{"Ending":get(g,"Ending")})
    annotate(g,"C-02: validate simulated registration facts; boss defeat only unlocks access. No file actor, confirmation UI, ending screen, input lock, or Retake logic is implemented.")
    g=edit(manager,"ProcessStoryEvent")
    remaining=g.find_graph_entry_pin()
    routes={}
    for event in ("JackFound","EscapeRouteOpened","JackReachedRefuge","EvidenceCollected","TruthRevealed","SupervisorEncounterStarted","SupervisorDefeated","FinalDocumentRegistered"):
        routes[event],remaining=branch(g,remaining,predicate(g,"EqualEqual_ByteByte",param(g,"Event"),EVENTS[event]["index"]))
    phase_rules=[
      ("JackFound","FindJack",[], "bJackFound","OpenEscapeRoute"),
      ("EscapeRouteOpened","OpenEscapeRoute",["bJackFound"],"bEscapeRouteOpen","ProtectJack"),
      ("JackReachedRefuge","ProtectJack",["bJackFound","bEscapeRouteOpen"],"bJackSafe","DiscoverTruth")]
    for event,phase,prereqs,flag,next_phase in phase_rules:
        cond=both(g,phase_is(g,phase),*[get(g,f) for f in prereqs],negate(g,get(g,flag)))
        allowed,_=branch(g,routes[event],cond)
        commit(g,setvar(g,allowed,flag,True),next_phase)
    invoke(g,routes["EvidenceCollected"],manager,"TryRecordEvidence",{"Param":param(g,"Param")})
    cond=both(g,phase_is(g,"DiscoverTruth"),get(g,"bJackSafe"),get(g,"bEvidenceFound"),get(g,"bFalseReportFound"))
    allowed,_=branch(g,routes["TruthRevealed"],cond)
    commit(g,allowed,"FinalChoice")
    for event,flag in (("SupervisorEncounterStarted","bSupervisorEncountered"),("SupervisorDefeated","bSupervisorDefeated")):
        allowed,_=branch(g,routes[event],both(g,phase_is(g,"FinalChoice"),negate(g,get(g,flag))))
        emit(g,setvar(g,allowed,flag,True),"OnChecklistUpdated")
    invoke(g,routes["FinalDocumentRegistered"],manager,"TryRegisterFinalDocument",{"Param":param(g,"Param")})
    annotate(g,"C-02: apply the prepared guarded transition table. Unhandled notifications, premature reports, invalid parameters, and duplicates do not advance phase.")
    compile_blueprint(manager,warnings_as_errors=True)
    # Existing GameState owns the component. Preserve its GetObjectiveManager implementation.
    g=edit(state,"GetCurrentPhase")
    assert all(n.get_class().get_name() in ("K2Node_FunctionEntry","K2Node_FunctionResult") for n in g.list_all_nodes()),"Preserve authored phase getter"
    entry=g.find_graph_entry_pin()
    result=next(n for n in g.list_all_nodes() if n.get_class().get_name()=="K2Node_FunctionResult")
    for p in list(entry.list_connected_pins()):entry.break_single_pin_link(p)
    end,node=invoke(g,entry,manager,"GetStoryPhase",target=get(g,"BP_ObjectiveManager"))
    connect(end,result.find_execute_pin());connect(node.find_result_pin(),result.find_input_pin("Result"))
    eg=unreal.BlueprintGraphEditor.get_graph_editor(unreal.BlueprintEditorLibrary.find_event_graph(state))
    before={n.get_path_name() for n in eg.list_all_nodes()}
    event=unreal.BlueprintEditorLibrary.add_event_override(state,"ReportStoryEvent",unreal.IntPoint(0,0))
    assert event
    assert not event.find_then_pin().list_connected_pins(),"Preserve authored story event handler"
    invoke(eg,event.find_then_pin(),manager,"HandleStoryEvent",{name:event.find_output_pin(name) for name,typ in inputs},target=get(eg,"BP_ObjectiveManager"))
    annotate(eg,"C-01: BPI_StoryEvents forwards reports to the existing ObjectiveManager. GameState never writes CurrentPhase.")
    compile_blueprint(state,warnings_as_errors=True)
    compile_blueprint(mode,warnings_as_errors=True)
    for bp in (manager,state):
        assert unreal.EditorAssetLibrary.save_loaded_asset(bp,False)
        OUT["saved"].append(bp.get_path_name())
    OUT["passed"]=True
except Exception:
    OUT["error"]=traceback.format_exc()
finally:
    target=Path(unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_dir())).parent/"Scripts/C/c01_c02_build_result.json"
    target.write_text(json.dumps(OUT,indent=2),encoding="utf-8")
    print("C_F1_BUILD "+json.dumps(OUT))
