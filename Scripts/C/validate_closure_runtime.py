"""Real-player Block 1 checks. Any health fixture exists only in PIE.

Stages run separately so native keyboard input and real world timers can advance.
"""
import unreal,json,traceback,sys
from pathlib import Path
sys.dont_write_bytecode=True
repo=Path(unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_dir())).parent
file=repo/'Scripts/C/closure_runtime_validation.json'
OUT=json.loads(file.read_text(encoding='utf-8')) if file.exists() and globals().get('C_STAGE')!='setup' else {'checks':[],'foreign_blockers':[]}
stage=globals().get('C_STAGE','setup')
def p(obj,name):return obj.get_editor_property(name)
def check(name,ok):
 OUT['checks'].append({'name':name,'passed':bool(ok),'stage':stage});assert ok,name
def component(path):return pawn.get_component_by_class(unreal.load_asset('/Game/Unscripted/'+path).generated_class())
try:
 world=unreal.EditorLevelLibrary.get_pie_worlds(False)[0]
 pawn=unreal.GameplayStatics.get_player_pawn(world,0);pc=unreal.GameplayStatics.get_player_controller(world,0)
 hud=pc.get_hud();view=p(hud,'View');state=unreal.GameplayStatics.get_game_state(world);manager=state.call_method('GetObjectiveManager');mode=unreal.GameplayStatics.get_game_mode(world)
 health=component('Player/BP_HealthComponent');temporal=component('Player/BP_TemporalComponent');interaction=component('Narrative/BP_InteractionComponent')
 if stage=='setup':
  check('Whitechapel uses the real A player',pawn.get_class().get_path_name()=='/Game/Unscripted/Player/BP_PlayerCharacter.BP_PlayerCharacter_C')
  check('C HUD is present and uses the real health component',view.is_in_viewport() and health is not None)
  check('Initial orders and checklist are visible',p(view,'DialogueView').is_visible() and p(view,'ChecklistView').is_visible())
  check('Protective initial directives are intact',str(p(p(view,'ChecklistView'),'ItemText0').get_text())=='Locate Jack.' and 'Protect Jack' in str(p(p(view,'ChecklistView'),'ItemText1').get_text()))
  check('CP0 is selected from the Story level',str(p(mode,'CheckpointId'))=='CP0')
  check('Production test hints remain hidden',not p(view,'TestHintBackdrop').is_visible())
  if p(health,'MaxHealth')<=0:OUT['foreign_blockers'].append('A: the real character health component template overrides MaxHealth and CurrentHealth to zero.')
  maximum=p(health,'MaxHealth');current=p(health,'CurrentHealth')
  actual=p(p(view,'HealthBar'),'percent')
  check('Initial HUD reflects the real health state',
        (str(p(view,'HealthValueText').get_text())=='UNAVAILABLE' and actual==0)
        if maximum<=0 else abs(actual-max(0,min(current/maximum,1)))<.001)
  OUT['initial_row']=str(p(manager,'CurrentDialogueRow'))
  # A transient, explicitly recorded fixture enables verification of the actual damage method.
  health.set_editor_property('MaxHealth',100.0,unreal.PropertyAccessChangeNotifyMode.NEVER);health.call_method('SetHealth',args=(100.0,))
  check('Real SetHealth updates numeric health and bar',str(p(view,'HealthValueText').get_text())=='100 / 100' and p(p(view,'HealthBar'),'percent')==1)
  health.call_method('ApplyHealthDamage',args=(25.0,))
  check('Real damage updates the HUD to 75 percent',p(health,'CurrentHealth')==75 and abs(p(p(view,'HealthBar'),'percent')-.75)<.001 and str(p(view,'HealthValueText').get_text())=='75 / 100')
  material=p(view,'AgentVitalsRing').get_dynamic_material()
  check('The circular health material receives the same live fraction',abs(material.get_scalar_parameter_value('HealthPercent')-.75)<.001)
  OUT['health_fixture']='PIE only: MaxHealth=100; the player asset and component template are never saved.'
  unreal.get_default_object(unreal.load_class(None,'/Script/UMG.WidgetBlueprintLibrary')).call_method('SetFocusToGameViewport')
 elif stage=='keyboard':
  check('Native E advances the real opening transmission',str(p(manager,'CurrentDialogueRow'))!=OUT['initial_row'])
  check('Native Tab hides the actual checklist',not p(view,'ChecklistView').is_visible())
  hud.call_method('ToggleChecklist')
  for _ in range(12):
   if not p(manager,'bDialogueActive'):break
   hud.call_method('UseNarrativeInteraction')
  check('The full opening transmission can be completed',not p(manager,'bDialogueActive'))
  check('Opening transmission does not advance the story prematurely',state.call_method('GetCurrentPhase').value==0)
  OUT['before_retake']=p(pawn,'RetakeCharges')
  OUT['before_retake_position']=list(pawn.get_actor_location().to_tuple())
  # The actual player history is generated by A's Tick, not by C's test player.
  check('Real personal Retake history is available',len(p(pawn,'PosHistory'))>0)
  unreal.get_default_object(unreal.load_class(None,'/Script/UMG.WidgetBlueprintLibrary')).call_method('SetFocusToGameViewport')
 elif stage=='retake':
  check('Native R consumes one charge on the real player',p(pawn,'RetakeCharges')==OUT['before_retake']-1)
  check('Real temporal dispatcher updates the HUD counter',str(p(view,'RetakeText').get_text()).startswith('Retake 1 / 2'))
  check('Charge pips show exactly one available charge',p(view,'RetakePip0').get_render_opacity()==1 and p(view,'RetakePip1').get_render_opacity()<.2)
  guardclass=unreal.load_asset('/Game/Unscripted/Enemies/BP_Pursuer').generated_class()
  guards=unreal.GameplayStatics.get_all_actors_of_class(world,guardclass)
  check('Integrated map has real pursuers for the F test',len(guards)>0)
  # Move the player only in PIE to a real encounter; never move or save B's actors.
  pawn.set_actor_location(guards[0].get_actor_location()+unreal.Vector(180,0,0),False,True)
  unreal.get_default_object(unreal.load_class(None,'/Script/UMG.WidgetBlueprintLibrary')).call_method('SetFocusToGameViewport')
 elif stage=='cut_started':
  check('Native F triggers the real temporal ability',not p(pawn,'bCutReady'))
  check('Real temporal dispatcher starts the visual cooldown',0<p(p(view,'CutCooldownBar'),'percent')<=1 and str(p(view,'CutStateText').get_text())!='READY')
  OUT['cut_percent']=p(p(view,'CutCooldownBar'),'percent')
  # Return to a safe place while the real gameplay cooldown continues.
  pawn.set_actor_location(unreal.Vector(300,1800,100),False,True)
 elif stage=='cut_finished':
  check('Gameplay and HUD both return to ready',p(pawn,'bCutReady') and p(p(view,'CutCooldownBar'),'percent')==0 and str(p(view,'CutStateText').get_text())=='READY')
  check('The player remains in the initial phase after ability tests',state.call_method('GetCurrentPhase').value==0)
  checkpoints=unreal.GameplayStatics.get_all_actors_of_class(world,unreal.load_asset('/Game/Unscripted/Narrative/BP_Checkpoint').generated_class())
  cp=next(x for x in checkpoints if str(p(x,'CheckpointId'))=='CP1')
  pawn.set_actor_location(cp.get_actor_location()+unreal.Vector(100,0,100),False,True)
  interaction.call_method('RefreshFocus');hud.call_method('RefreshInteractionPrompt')
  check('Real interaction component focuses CP1',p(interaction,'FocusedActor')==cp)
  check('World checkpoint prompt is readable on the real HUD','checkpoint' in str(p(view,'InteractionText').get_text()).lower())
  OUT['cp1']=cp.get_path_name()
  unreal.get_default_object(unreal.load_class(None,'/Script/UMG.WidgetBlueprintLibrary')).call_method('SetFocusToGameViewport')
 elif stage=='checkpoint':
  check('Native E records CP1 through the existing contracts',str(p(mode,'CheckpointId'))=='CP1')
  check('The saved respawn point is raised above the ground',p(mode,'RespawnTransform').translation.z>=99)
  hides=unreal.GameplayStatics.get_all_actors_of_class(world,unreal.load_asset('/Game/Unscripted/Narrative/BP_Hideout').generated_class())
  hide=hides[0];pawn.set_actor_location(hide.get_actor_location()+unreal.Vector(140,0,100),False,True)
  interaction.call_method('RefreshFocus')
  check('The placed wardrobe is focused by the real player',p(interaction,'FocusedActor')==hide)
  hud.call_method('UseNarrativeInteraction')
  stealth=component('Enemies/BP_StealthComponent')
  check('Wardrobe hides the real player through the published stealth API',p(hide,'bOccupied') and p(stealth,'bIsHidden'))
  hud.call_method('UseNarrativeInteraction')
  check('Wardrobe exits without trapping the player',not p(hide,'bOccupied') and not p(stealth,'bIsHidden') and not pc.is_move_input_ignored())
  before=p(mode,'RestoreCount');mode.call_method('RestoreCheckpoint')
  check('C broadcasts the checkpoint restore without resetting the story',p(mode,'RestoreCount')==before+1 and state.call_method('GetCurrentPhase').value==0)
  if pawn.get_actor_location().distance(p(mode,'RespawnTransform').translation)>2:OUT['foreign_blockers'].append('A: real player does not implement checkpoint restoration; C broadcasts the correct listener event but the player is not repositioned.')
  player_bp=unreal.load_asset('/Game/Unscripted/Player/BP_PlayerCharacter')
  die=next((g for g in unreal.BlueprintEditorLibrary.list_graphs(player_bp) if g.get_name()=='Die'),None)
  if die:
   nodes=unreal.BlueprintGraphEditor.get_graph_editor(die).list_all_nodes()
   for node in nodes:
    if node.get_class().get_name()=='K2Node_Message' and 'ReportStoryEvent' in str(node.get_node_title()).replace(' ',''):
     pin=node.find_input_pin('Event')
     if pin.is_valid() and pin.get_pin_value()=='NewEnumerator0':OUT['foreign_blockers'].append('A: Die reports JackFound rather than PlayerDefeated.')
    if node.get_class().get_name()=='K2Node_CallFunction':
     pin=node.find_input_pin('FunctionName')
     if pin.is_valid() and pin.get_pin_value()=='RestartLevel':OUT['foreign_blockers'].append('A: Die still schedules a level reload instead of checkpoint restoration.')
  jack=unreal.load_asset('/Game/Unscripted/Enemies/Jack/BP_Jack')
  if not jack or not unreal.GameplayStatics.get_all_actors_of_class(world,jack.generated_class()):OUT['foreign_blockers'].append('B: no Jack is placed in the integrated Story/AI world, so the Block 1 exit route cannot be played through.')
  OUT['finished']=True
 OUT['last_stage']=stage
except Exception:
 OUT['error']=traceback.format_exc();unreal.log_error(OUT['error'])
finally:
 OUT['passed']=not OUT.get('error') and bool(OUT.get('finished'))
 OUT['check_count']=len(OUT['checks']);file.write_text(json.dumps(OUT,indent=2),encoding='utf-8')
 print('C_CLOSURE_RUNTIME_VALIDATION '+json.dumps(OUT))
