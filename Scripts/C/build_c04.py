"""C-04: reusable interactables, persistent door, and reversible hideout."""
import sys,json,traceback
from pathlib import Path
import unreal
repo=Path(unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_dir())).parent
sys.path.insert(0,str(repo/"Scripts/C"))
import blueprint_helpers_c as h
from importlib import reload
h=reload(h)
OUT={"passed":False,"saved":[]}
try:
    base=h.asset("Narrative/BP_InteractableBase")
    actor=h.obj_type(unreal.Actor);boolean=h.basic("bool");text=h.basic("text");integer=h.basic("int")
    for name,typ,default,editable in (("bInteractionEnabled",boolean,True,True),("bConsumed",boolean,False,False),("InteractionPriority",integer,"40",True),("InteractionPrompt",text,"Interact",True),("InteractionCount",integer,"0",False),("LastInteractor",actor,"",False)):
        h.variable(base,name,typ,default,editable,"Interaction")
    execute=h.function(base,"ExecuteInteraction",[("Interactor",actor)],replace=True)
    execute.set_function_is_protected()
    report=h.function(base,"ReportStoryFact",[("Event",h.enum_type("EStoryEvent")),("Param",h.basic("name"))],replace=True)
    h.compile_blueprint(base,warnings_as_errors=True)
    for name in ("CanInteract","GetInteractionText","GetInteractionPriority"):
        g=h.override(base,name)
        assert all(n.get_class().get_name() in ("K2Node_FunctionEntry","K2Node_FunctionResult") for n in g.list_all_nodes()),"Preserve authored interactable body"
        h.clear_body(g)
        if name=="CanInteract":
            test=h.all_true(g,h.get(g,"bInteractionEnabled"),h.not_(g,h.get(g,"bConsumed")),h.is_valid(g,h.param(g,"Interactor")))
            h.result(g,g.find_graph_entry_pin(),Result=test)
        elif name=="GetInteractionText":h.result(g,g.find_graph_entry_pin(),Result=h.get(g,"InteractionPrompt"))
        else:h.result(g,g.find_graph_entry_pin(),Result=h.get(g,"InteractionPriority"))
    g,event=h.event(base,"Interact")
    assert not event.find_then_pin().list_connected_pins(),"Preserve authored Interact event"
    actor_pin=event.find_output_pin("Interactor")
    can=h.invoke(g,event.find_then_pin(),base,"CanInteract",Interactor=actor_pin)
    yes,_=h.branch(g,can.find_then_pin(),can.find_result_pin())
    end=h.setvar(g,yes,"InteractionCount",h.math(g,"Add_IntInt",h.get(g,"InteractionCount"),1))
    end=h.setvar(g,end,"LastInteractor",actor_pin)
    h.invoke(g,end,base,"ExecuteInteraction",Interactor=actor_pin)
    g=h.edit(base,"ReportStoryFact")
    state=h.call(g,"/Script/Engine.GameplayStatics:GetGameState").find_result_pin()
    yes,_=h.branch(g,g.find_graph_entry_pin(),h.is_valid(g,state))
    h.message(g,yes,"ReportStoryEvent",state,Event=h.param(g,"Event"),Source=h.self_pin(g),Param=h.param(g,"Param"))
    h.save(base);OUT["saved"].append(base.get_path_name())
    door=h.asset("Narrative/BP_Door")
    h.variable(door,"bIsOpen",boolean,False)
    h.variable(door,"bReportsEscapeRoute",boolean,True,True)
    mesh=h.add_component(door,"DoorMesh",unreal.StaticMeshComponent)
    mesh.set_static_mesh(unreal.load_asset("/Engine/BasicShapes/Cube"))
    mesh.set_editor_property("relative_scale3d",unreal.Vector(0.18,1.2,2.0))
    mesh.set_editor_property("relative_location",unreal.Vector(0,0,100))
    mesh.set_editor_property("mobility",unreal.ComponentMobility.MOVABLE)
    cdo=unreal.get_default_object(door.generated_class())
    cdo.set_editor_property("InteractionPrompt","Open escape route")
    cdo.set_editor_property("InteractionPriority",40)
    g=h.override(door,"ExecuteInteraction");h.clear_body(g)
    end=h.setvar(g,g.find_graph_entry_pin(),"bIsOpen",True)
    end=h.setvar(g,end,"bConsumed",True)
    rot=h.call(g,"/Script/Engine.SceneComponent:K2_SetRelativeRotation",start=end,target=h.get(g,"DoorMesh"),NewRotation="(Pitch=0,Yaw=90,Roll=0)",bSweep=False,bTeleport=True)
    collision=h.call(g,"/Script/Engine.Actor:SetActorEnableCollision",start=rot.find_then_pin(),bNewActorEnableCollision=False)
    clear=h.message(g,collision.find_then_pin(),"ClearRetakeHistory",h.param(g,"Interactor"))
    yes,_=h.branch(g,clear.find_then_pin(),h.get(g,"bReportsEscapeRoute"))
    h.invoke(g,yes,base,"ReportStoryFact",Event="NewEnumerator1",Param="")
    h.save(door);OUT["saved"].append(door.get_path_name())
    hide=h.asset("Narrative/BP_Hideout")
    h.variable(hide,"bOccupied",boolean,False)
    h.variable(hide,"Occupant",actor,"")
    mesh=h.add_component(hide,"HideoutMesh",unreal.StaticMeshComponent)
    mesh.set_static_mesh(unreal.load_asset("/Engine/BasicShapes/Cube"))
    mesh.set_editor_property("relative_scale3d",unreal.Vector(1.2,1.2,2.1))
    mesh.set_editor_property("relative_location",unreal.Vector(0,0,105))
    mesh.set_editor_property("mobility",unreal.ComponentMobility.MOVABLE)
    cdo=unreal.get_default_object(hide.generated_class())
    cdo.set_editor_property("InteractionPrompt","Enter hideout");cdo.set_editor_property("InteractionPriority",30)
    g=h.override(hide,"ExecuteInteraction");h.clear_body(g)
    end=h.setvar(g,g.find_graph_entry_pin(),"bOccupied",h.not_(g,h.get(g,"bOccupied")))
    end=h.setvar(g,end,"Occupant",h.param(g,"Interactor"))
    component=h.message(g,end,"GetStealthComponent",h.param(g,"Interactor"))
    yes,_=h.branch(g,component.find_then_pin(),h.is_valid(g,component.find_result_pin()))
    stealth=h.asset("Enemies/BP_StealthComponent")
    call=h.invoke(g,yes,stealth,"SetHidden",target=component.find_result_pin(),bHidden=h.get(g,"bOccupied"))
    block=h.message(g,call.find_then_pin(),"SetRetakeBlocked",h.param(g,"Interactor"),bBlocked=h.get(g,"bOccupied"))
    pc=h.call(g,"/Script/Engine.GameplayStatics:GetPlayerController",PlayerIndex=0).find_result_pin()
    move=h.call(g,"/Script/Engine.Controller:SetIgnoreMoveInput",start=block.find_then_pin(),target=pc,bNewMoveInput=h.get(g,"bOccupied"))
    yes,no=h.branch(g,move.find_then_pin(),h.get(g,"bOccupied"))
    h.setvar(g,yes,"InteractionPrompt","Leave hideout")
    end=h.setvar(g,no,"InteractionPrompt","Enter hideout");h.setvar(g,end,"Occupant",None)
    h.layout(base);h.layout(door);h.layout(hide)
    h.save(base,door,hide)
    OUT["saved"].append(hide.get_path_name());OUT["passed"]=True
except Exception:OUT["error"]=traceback.format_exc()
finally:
    (repo/"Scripts/C/c04_build_result.json").write_text(json.dumps(OUT,indent=2),encoding="utf-8")
    print("C04_BUILD "+json.dumps(OUT))
